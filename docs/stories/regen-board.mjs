#!/usr/bin/env node
/**
 * Rebuild board-data.js from docs/stories/*.md frontmatter + body.
 * No deps: open board.html via file:// after running this.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const outFile = join(dir, "board-data.js");

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) {
    return { meta: {}, body: raw.trim() };
  }
  const meta = {};
  for (const line of match[1].split(/\r?\n/)) {
    const idx = line.indexOf(":");
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    const comment = value.indexOf(" #");
    if (comment !== -1) value = value.slice(0, comment).trim();
    meta[key] = value;
  }
  return { meta, body: match[2].trim() };
}

function previewFromBody(body) {
  const line =
    body
      .split(/\r?\n/)
      .map((l) => l.trim())
      .find((l) => l.startsWith("**Как**") || (l && !l.startsWith("#") && !l.startsWith("---"))) ??
    "";
  return line.replace(/\*\*/g, "").slice(0, 160);
}

function acceptanceFromBody(body) {
  const items = [];
  for (const line of body.split(/\r?\n/)) {
    const m = line.match(/^\d+\.\s+(.+)$/);
    if (m) items.push(m[1].trim());
  }
  return items;
}

const names = (await readdir(dir))
  .filter((n) => n.endsWith(".md") && n !== "README.md")
  .sort();

const stories = [];
for (const name of names) {
  const raw = await readFile(join(dir, name), "utf8");
  const { meta, body } = parseFrontmatter(raw);
  const status = meta.status || "backlog";
  if (!["backlog", "in_progress", "done"].includes(status)) {
    console.warn(`skip ${name}: unknown status "${status}"`);
    continue;
  }
  stories.push({
    id: meta.id || name.replace(/\.md$/, ""),
    title: meta.title || name.replace(/\.md$/, ""),
    status,
    branch: meta.branch || "",
    pr: meta.pr || "",
    external: meta.external || "",
    file: name,
    preview: previewFromBody(body),
    acceptance: acceptanceFromBody(body),
  });
}

const payload = `/* Generated by regen-board.mjs — do not edit by hand. */\nconst STORIES = ${JSON.stringify(stories, null, 2)};\n`;
await writeFile(outFile, payload, "utf8");
console.log(`Wrote ${stories.length} stor${stories.length === 1 ? "y" : "ies"} → ${outFile}`);
